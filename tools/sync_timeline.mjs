// Copies the scene timeline of the demonstration video into public/timeline.js (the page links each mechanism to its moment).
// Run after re-rendering the video:  node tools/sync_timeline.mjs
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
const src = '../modelau_latex/evaluation/demo/video/out/timeline.json';
const t = JSON.parse(readFileSync(src, 'utf8'));
writeFileSync('public/timeline.js', `// generated by tools/sync_timeline.mjs\nexport default ${JSON.stringify(t)};\n`);
writeFileSync('tools/timeline.json', JSON.stringify(t, null, 1));
for (const l of ['es', 'en']) copyFileSync(`../modelau_latex/evaluation/demo/video/out/modelau_demo_${l}.mp4`, `public/video/modelau_demo_${l}.mp4`);
console.log('timeline and videos synced:', Object.keys(t).join(' '));
